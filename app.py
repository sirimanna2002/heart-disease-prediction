import streamlit as st
import joblib
import numpy as np

# Load Model and Scaler
model = joblib.load('heart_disease_model.pkl')
scaler = joblib.load('scaler.pkl')

st.title("❤️ Heart Disease Risk Prediction")
st.write("Enter the patient’s clinical details and get an instant heart disease risk prediction.")

# Patient details include Form 
age = st.number_input("Age", min_value=20, max_value=100, value=50)
sex = st.selectbox("Sex", options=["Male", "Female"])
cp = st.selectbox("Chest Pain Type", options=[0, 1, 2, 3],
                   help="0=Typical Angina, 1=Atypical, 2=Non-anginal, 3=Asymptomatic")
trestbps = st.number_input("Resting Blood Pressure (mm Hg)", min_value=80, max_value=220, value=120)
chol = st.number_input("Cholesterol (mg/dl)", min_value=100, max_value=600, value=200)
fbs = st.selectbox("Fasting Blood Sugar > 120 mg/dl?", options=["No", "Yes"])
restecg = st.selectbox("Resting ECG Result", options=[0, 1, 2])
thalach = st.number_input("Max Heart Rate Achieved", min_value=60, max_value=220, value=150)
exang = st.selectbox("Exercise Induced Angina?", options=["No", "Yes"])
oldpeak = st.number_input("ST Depression (oldpeak)", min_value=0.0, max_value=7.0, value=1.0, step=0.1)
slope = st.selectbox("Slope of Peak Exercise ST Segment", options=[0, 1, 2])
ca = st.selectbox("Number of Major Vessels (0-4)", options=[0, 1, 2, 3, 4])
thal = st.selectbox("Thalassemia", options=[0, 1, 2, 3])

# Convert Text inputs numbers
sex_val = 1 if sex == "Male" else 0
fbs_val = 1 if fbs == "Yes" else 0
exang_val = 1 if exang == "Yes" else 0

if st.button("Predict Risk"):
    input_data = np.array([[age, sex_val, cp, trestbps, chol, fbs_val, restecg,
                             thalach, exang_val, oldpeak, slope, ca, thal]])
    input_scaled = scaler.transform(input_data)
    prediction = model.predict(input_scaled)[0]
    probability = model.predict_proba(input_scaled)[0][1]

    st.write("---")
    if prediction == 1:
        st.error(f"⚠️ High Risk of Heart Disease Detected (Probability: {probability:.1%})")
    else:
        st.success(f"✅ Low Risk of Heart Disease (Probability: {probability:.1%})")

    st.caption("Note: This is only an estimate generated by an ML model. It is not a medical diagnosis. Please consult a qualified doctor for actual medical advice.")